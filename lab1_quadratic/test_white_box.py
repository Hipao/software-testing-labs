"""Тестирование методом «белого ящика»: покрытие всех 8 ветвей функции solve (покрытие ветвей и условий)."""
import pytest
from quadratic import solve

WHITE = [
    # (№, назначение, a, b, c, ожидаемый вид, ожидаемые корни)
    ("W1", "a=0, b=0, c=0 — ветви 1, 2, 3", 0, 0, 0, "бесконечно много решений", []),
    ("W2", "a=0, b=0, c≠0 — ветви 1, 2, 4", 0, 0, 5, "нет решений", []),
    ("W3", "a=0, b≠0 — ветви 1, 5", 0, 2, -4, "линейное уравнение", [2.0]),
    ("W4", "a≠0, D>0 — ветвь 6", 1, -3, 2, "два корня", [1.0, 2.0]),
    ("W5", "a≠0, D=0 — ветвь 7", 1, -2, 1, "один корень", [1.0]),
    ("W6", "a≠0, D<0 — ветвь 8", 1, 0, 1, "нет действительных корней", []),
    ("W7", "a<0, D>0 — знак a в знаменателе", -1, 0, 4, "два корня", [-2.0, 2.0]),
    ("W8", "a=0, b≠0, c=0 — нулевой корень без «-0»", 0, 3, 0, "линейное уравнение", [0.0]),
]


@pytest.mark.parametrize("tid,purpose,a,b,c,kind,roots", WHITE, ids=[w[0] for w in WHITE])
def test_branch(tid, purpose, a, b, c, kind, roots):
    got_kind, got_roots = solve(a, b, c)
    assert got_kind == kind
    assert got_roots == pytest.approx(roots)
